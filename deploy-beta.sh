#!/usr/bin/env bash
set -euo pipefail

# deploy-beta.sh - Full beta deployment for kant-pastebin
#
#   ./deploy-beta.sh              # build + install + restart + verify
#   ./deploy-beta.sh --no-build   # skip cargo build (binary already present)
#   ./deploy-beta.sh --port 8095  # use a different backend port
#
# What it does:
#   1. builds target/release/kant-pastebin (nix develop -> cargo build --release)
#   2. writes the nginx location block for /pastebin/beta/
#   3. installs it into the nginx services.d directory (sudo, if needed)
#   4. writes a systemd unit for the beta instance
#   5. installs + (re)starts the unit (systemd, else plain nohup fallback)
#   6. verifies the backend and the public URL answer
#
# Environment overrides:
#   BETA_PORT          backend port (default 8084)
#   PASTEBIN_DOMAIN    public domain (default solana.solfunmeme.com)
#   NGINX_SERVICES_DIR where nginx service snippets live
#   PASTEBIN_DIR       project root (default: script dir)

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
PASTEBIN_DIR="${PASTEBIN_DIR:-$SCRIPT_DIR}"
BETA_PORT="${BETA_PORT:-8085}"
DOMAIN="${PASTEBIN_DOMAIN:-solana.solfunmeme.com}"
NGINX_SERVICES_DIR="${NGINX_SERVICES_DIR:-/etc/nginx/services.d}"
NGINX_MERGED_DIR="${NGINX_MERGED_DIR:-/etc/nginx-sm-merged/services.d}"
UNIT_NAME="kant-pastebin-beta"
SNIPPET_NAME="pastebin-beta.conf"
BINARY="$PASTEBIN_DIR/target/release/kant-pastebin"
UUCP_SPOOL="${UUCP_SPOOL:-/mnt/data1/spool/uucp/pastebin}"

DO_BUILD=1
while [ $# -gt 0 ]; do
    case "$1" in
        --no-build) DO_BUILD=0; shift ;;
        --port) BETA_PORT="$2"; shift 2 ;;
        --port=*) BETA_PORT="${1#*=}"; shift ;;
        -h|--help) sed -n '2,30p' "$0"; exit 0 ;;
        *) echo "Unknown argument: $1" >&2; exit 1 ;;
    esac
done

log()  { echo "[$(date -u +%Y-%m-%dT%H:%M:%SZ)] $*"; }
section() { printf '\n=== %s ===\n' "$1"; }
die()  { echo "[$(date -u +%Y-%m-%dT%H:%M:%SZ)] ERROR: $*" >&2; exit 1; }

# Run a command with sudo only if we lack write access to the target.
as_root() {
    local target="$1"; shift
    if [ -w "$target" ]; then
        "$@"
    elif command -v sudo >/dev/null 2>&1 && sudo -n true 2>/dev/null; then
        sudo "$@"
    else
        die "need write access to $target (and passwordless sudo is unavailable)"
    fi
}

# ── 1. build ────────────────────────────────────────────────────────────────
cd "$PASTEBIN_DIR"
GIT_COMMIT="$(git rev-parse HEAD 2>/dev/null || echo unknown)"
BUILD_TIME="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
export GIT_COMMIT BUILD_TIME

if [ "$DO_BUILD" -eq 1 ]; then
    section "Build"
    log "commit=$GIT_COMMIT build_time=$BUILD_TIME"
    if command -v nix >/dev/null 2>&1; then
        nix develop -c cargo build --release
    else
        cargo build --release
    fi
fi
[ -x "$BINARY" ] || die "binary not found at $BINARY"
log "binary: $BINARY"

# ── 2. nginx snippet ────────────────────────────────────────────────────────
section "Nginx snippet"
mkdir -p "$PASTEBIN_DIR/nginx-beta"
SNIPPET="$PASTEBIN_DIR/nginx-beta/$SNIPPET_NAME"

cat > "$SNIPPET" <<NGINX_EOF
# Kant Pastebin Beta Site — /pastebin/beta/
# Generated by deploy-beta.sh — do not edit by hand.

location /pastebin/beta/ {
    proxy_pass http://127.0.0.1:${BETA_PORT}/;
    proxy_http_version 1.1;
    proxy_set_header Host \$host;
    proxy_set_header X-Real-IP \$remote_addr;
    proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto \$scheme;

    add_header X-Pastebin-Beta-Version "v0.2.0";
    add_header X-Pastebin-Beta-Commit "${GIT_COMMIT}";
    add_header X-Pastebin-Beta-Port "${BETA_PORT}";

    client_max_body_size 0;
    proxy_read_timeout 3600s;
    proxy_send_timeout 3600s;
    proxy_connect_timeout 3600s;
    proxy_buffering off;
    proxy_request_buffering off;
    charset utf-8;
}
NGINX_EOF
log "wrote $SNIPPET"

# ── 3. install snippet into nginx ───────────────────────────────────────────
section "Install nginx snippet"
INSTALLED=0
for dir in "$NGINX_MERGED_DIR" "$NGINX_SERVICES_DIR"; do
    [ -d "$dir" ] || continue
    dest="$dir/$SNIPPET_NAME"
    # Drop any previous copy so we do not append duplicates on re-runs.
    if [ -f "$dest" ] && ! grep -q "location /pastebin/beta/" "$dest" 2>/dev/null; then
        as_root "$dest" cp "$dest" "$dest.bak.$(date -u +%Y%m%d%H%M%S)"
    fi
    as_root "$dir" sh -c "cat '$SNIPPET' > '$dest'"
    log "installed $dest"
    INSTALLED=1
done
[ "$INSTALLED" -eq 1 ] || die "no nginx services directory found (looked in $NGINX_MERGED_DIR, $NGINX_SERVICES_DIR)"

# ── 4. systemd unit ─────────────────────────────────────────────────────────
section "Systemd unit"
UNIT_SRC="$PASTEBIN_DIR/$UNIT_NAME.service"
cat > "$UNIT_SRC" <<UNIT_EOF
[Unit]
Description=Kant Pastebin Beta (commit ${GIT_COMMIT})
After=network.target

[Service]
Type=simple
WorkingDirectory=$PASTEBIN_DIR
ExecStart=$BINARY
Restart=always
RestartSec=10
Environment="UUCP_SPOOL=$UUCP_SPOOL"
Environment="BIND_ADDR=127.0.0.1:${BETA_PORT}"
Environment="PORT=${BETA_PORT}"
Environment="BASE_PATH=/pastebin/beta"
Environment="BASE_URL=https://${DOMAIN}"
Environment="RUST_LOG=info"
Environment="GIT_COMMIT=${GIT_COMMIT}"
Environment="BUILD_TIME=${BUILD_TIME}"
TimeoutStartSec=0
TimeoutStopSec=0
NoNewPrivileges=true
PrivateTmp=true
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true

[Install]
WantedBy=default.target
UNIT_EOF
log "wrote $UNIT_SRC"

UNIT_DIR=""
for d in /etc/systemd/system "$HOME/.config/systemd/user"; do
    [ -d "$d" ] && UNIT_DIR="$d" && break
done
[ -n "$UNIT_DIR" ] || die "no systemd unit directory found"

if command -v systemctl >/dev/null 2>&1; then
    as_root "$UNIT_DIR" cp "$UNIT_SRC" "$UNIT_DIR/$UNIT_NAME.service"
    log "installed $UNIT_DIR/$UNIT_NAME.service"
    systemctl daemon-reload >/dev/null 2>&1 || sudo systemctl daemon-reload
    # stop needs root on this host; without the sudo fallback the old process
    # kept running and "start" was a no-op, so a redeploy never took effect.
    systemctl stop "$UNIT_NAME" >/dev/null 2>&1 \
        || sudo systemctl stop "$UNIT_NAME" >/dev/null 2>&1 || true
    systemctl start "$UNIT_NAME" 2>/dev/null || sudo systemctl start "$UNIT_NAME"
    log "started $UNIT_NAME via systemd"
else
    die "systemctl not available"
fi

# ── 5. verify ───────────────────────────────────────────────────────────────
section "Verify"
sleep 3
BACKEND="http://127.0.0.1:${BETA_PORT}"
if ! curl -fsS --max-time 10 "$BACKEND/api/version" >/dev/null; then
    log "backend did not answer, falling back to nohup"
    pkill -f "kant-pastebin --bind 0.0.0.0 --port ${BETA_PORT}" 2>/dev/null || true
    sleep 1
    ( cd "$PASTEBIN_DIR" && UUCP_SPOOL="$UUCP_SPOOL" BASE_PATH=/pastebin \
        BASE_URL="https://${DOMAIN}" RUST_LOG=info GIT_COMMIT="$GIT_COMMIT" \
        BUILD_TIME="$BUILD_TIME" \
        nohup "$BINARY" --bind 0.0.0.0 --port "$BETA_PORT" \
        > /tmp/kant-pastebin-beta.log 2>&1 & )
    sleep 4
fi

log "backend version:"
curl -fsS --max-time 10 "$BACKEND/api/version" || die "backend not answering on $BACKEND"

# Reload nginx so the new location block takes effect.
if command -v systemctl >/dev/null 2>&1; then
    systemctl reload nginx 2>/dev/null || sudo systemctl reload nginx \
        || { log "nginx reload failed — trying nginx -s reload"; sudo nginx -s reload 2>/dev/null || true; }
    log "nginx reloaded"
fi

PUBLIC="https://${DOMAIN}/pastebin/beta/api/version"
log "public URL: $PUBLIC"
if curl -fsS --max-time 20 "$PUBLIC"; then
    log "public beta reachable"
else
    log "public beta not reachable yet (nginx may still be reloading); backend is fine at $BACKEND"
fi

section "Summary"
log "version:    v0.2.0 (${GIT_COMMIT:0:7})"
log "backend:    $BACKEND"
log "public:     https://${DOMAIN}/pastebin/beta/"
log "nginx:      $SNIPPET"
log "unit:       $UNIT_DIR/$UNIT_NAME.service"
log "log:        journalctl -u $UNIT_NAME -f"
