// scripts/lean-to-thunk.mjs — compile Lean code to thunks
//
// Transforms Lean 4 pure functions to thunks for the thunk system.
// Currently supports text splitting algorithm from lean4/Splitter.lean

import fs from "node:fs";
import path from "node:path";

const SPLITTER_PATH = path.join(process.cwd(), "lean4/Splitter.lean");

async function compileLeanSplitterToThunk() {
  const source = await fs.promises.readFile(SPLITTER_PATH, "utf8");
  
  // Extract key functions for text splitting
  const thunkSource = `// Thunkified from: lean4/Splitter.lean
// Text splitting algorithm with Lean-style input parameters
// Generated by scripts/lean-to-thunk.mjs

const MAX_CHUNK_SIZE = 4096;

// Pure text splitting function equivalent to splitText
function splitText(chunkSize, unit, text) {
  // unit: "byte", "word", or "token" (String instead of Lean Unit)
  
  // Convert string to characters (similar to bytesOfText)
  const bytes = Array.from(text).map(c => c.charCodeAt(0));
  
  // Helper: is whitespace character
  function isWhitespace(b) {
    return b === 32 || b === 9 || b === 10 || b === 13; // space, tab, newline, carriage return
  }
  
  // Helper: token length in bytes/characters (similar to tokenLen)
  function tokenLen(bs) {
    if (bs.length === 0) return 0;
    if (isWhitespace(bs[0])) return 0;
    return 1 + tokenLen(bs.slice(1));
  }
  
  // Helper: whitespace length (similar to whitespaceLen)
  function whitespaceLen(bs) {
    if (bs.length === 0) return 0;
    if (isWhitespace(bs[0])) return 1 + whitespaceLen(bs.slice(1));
    return 0;
  }
  
  // State management (similar to State structure)
  function State() {
    this.chunks = [];
    this.start = 0;
    this.measure = 0;
  }
  
  // Step function (similar to Lean step)
  function step(chunkSize, u, st, bs) {
    const word = bs.slice(0, tokenLen(bs));
    const afterWhitespace = bs.slice(tokenLen(bs) + whitespaceLen(bs.slice(tokenLen(bs))));
    const wordMeasure = u === "byte" ? word.length :
                       u === "word" ? word.length :
                       word.length;
    
    if (wordMeasure > chunkSize) {
      if (st.measure > 0 && st.start < bs.length) {
        st.chunks.push(bs.slice(0, st.start));
      }
      st.start = afterWhitespace.length;
      st.measure = 0;
    } else if (st.measure > 0 && st.measure + wordMeasure > chunkSize) {
      if (st.start < bs.length) {
        st.chunks.push(bs.slice(0, st.start));
      }
      st.start = word.length;
      st.measure = wordMeasure;
    } else {
      st.measure = st.measure + wordMeasure;
    }
    return st;
  }
  
  // Main splitting function (similar to splitWords)
  function splitWords(chunkSize, u, bs) {
    function go(st, rest) {
      if (rest.length === 0) {
        if (st.start < bs.length) {
          st.chunks.push(bs.slice(st.start));
        }
        return st.chunks;
      }
      const next = step(chunkSize, u, st, rest);
      return go(next, rest.slice(1));
    }
    const initial = { chunks: [], start: 0, measure: 0 };
    return go(initial, bs);
  }
  
  // Convert text to bytes (similar to bytesOfText)
  function bytesOfText(s) {
    return Array.from(s).map(c => c.charCodeAt(0));
  }
  
  // Convert bytes to text (similar to textOfBytes)
  function textOfBytes(bs) {
    return bs.map(b => String.fromCharCode(b % 256)).join('');
  }
  
  // Split text (equivalent to Lean's splitText)
  function splitText(chunkSize, u, s) {
    const chunks = splitWords(chunkSize, u, bytesOfText(s));
    return chunks.map(textOfBytes).filter(x => x !== "");
  }
  
  // Unit measurement (similar to Unit.measureWord)
  function measureWord(u, w) {
    if (u === "byte") return w;
    if (u === "word") return w;
    return 1; // token
  }
  
  // Main reduce function for thunk
  function reduce(state, input) {
    const s = state || { initialized: false, data: null, lastUpdate: 0 };
    
    switch (input?.type) {
      case "split_text": {
        const { chunkSize, unit, text } = input.data || {};
        const result = splitText(chunkSize, unit, text);
        return {
          ...s,
          initialized: true,
          data: { result, chunkSize, unit, text },
          lastUpdate: Date.now(),
        };
      }
      case "init": {
        return { ...state, initialized: true, lastUpdate: Date.now() };
      }
      case "query": {
        return { ...s };
      }
      case "snapshot": {
        return {
          initialized: s.initialized,
          data: s.data,
          lastUpdate: s.lastUpdate,
        };
      }
      case "reset": {
        return { initialized: false, data: null, lastUpdate: 0 };
      }
      default:
        return s;
    }
  }
  
  module.exports = { 
    reduce, 
    initialState: { initialized: false, data: null, lastUpdate: 0 } 
  };
`;
  
  console.log(`[lean-to-thunk] Generated thunk for Lean Splitter.lean`);
  return thunkSource;
}

// Export compilation function
export { compileLeanSplitterToThunk };
